import { build } from "esbuild";
import { mkdir, readFile, writeFile, rm, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
const pkg = JSON.parse(await readFile("package.json", "utf8"));
await mkdir("public/tools", { recursive: true });
await build({
  entryPoints: ["src/analysis.worker.ts"],
  outfile: "public/tools/bundle.js",
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  external: ["fs", "path", "crypto"],
});
const bytes = await readFile("public/tools/bundle.js");
const hash = createHash("sha256").update(bytes).digest("hex");
const filename = `analysis-${hash.slice(0, 20)}.js`;
await writeFile(`public/tools/${filename}`, bytes);
// Delete only superseded files generated by this script, never arbitrary tools.
for (const existing of await readdir("public/tools")) {
  if (/^analysis-[a-f0-9]{20}\.js$/.test(existing) && existing !== filename)
    await rm(`public/tools/${existing}`);
}
await rm("public/tools/bundle.js");
await writeFile(
  "public/tools/manifest.json",
  JSON.stringify(
    {
      tools: [
        {
          id: "wret-static",
          version: pkg.version,
          formats: [
            "javascript",
            "html",
            "css",
            "json",
            "sourcemap",
            "wasm",
            "binary",
          ],
          entry: `/tools/${filename}`,
          integrity: hash,
          dependencies: pkg.dependencies,
        },
      ],
    },
    null,
    2,
  ),
);
console.log(`Built verified analysis bundle: ${filename}`);
